from pathlib import Path


def parse_header_files(index_xml: Path) -> list[str]:
    root = ET.parse(index_xml).getroot()
    headers: list[str] = []

    for compound in root.findall("compound"):
        if compound.attrib.get("kind") != "file":
            continue
        name = (compound.findtext("name") or "").strip()
        if name.endswith(".h"):
            headers.append(name)

    headers.sort()
    return headers


def page_slug(header: str) -> str:
    return Path(header).stem


def render_header_page(header: str, project: str) -> str:
    # Remove .h from the header, replace _ with whitespace and capitalize
    title = header.replace(".h", "").replace("_", " ").title()
    underline = "=" * len(title)
