def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--index-xml", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--project", default="HTTPServer")
    args = parser.parse_args()

    headers = parse_header_files(args.index_xml)

    api_dir = args.output.parent / "api"
    if api_dir.exists():
        shutil.rmtree(api_dir)
    api_dir.mkdir(parents=True, exist_ok=True)

    for header in headers:
        (api_dir / f"{page_slug(header)}.rst").write_text(
            render_header_page(header, args.project),
            encoding="utf-8",
        )

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render_api_index(headers), encoding="utf-8")

    index_page = args.output.parent / "index.rst"
    index_page.write_text(render_index_page(), encoding="utf-8")

    installation_rst = args.output.parent / "installation.rst"
    installation_rst.write_text(render_installation_page(), encoding="utf-8")

    testing_rst = args.output.parent / "testing.rst"
    testing_rst.write_text(render_testing_page(), encoding="utf-8")

    architecture_rst = args.output.parent / "architecture.rst"
    architecture_rst.write_text(render_architecture_page(), encoding="utf-8")

    metrics_rst = args.output.parent / "metrics.rst"
    metrics_rst.write_text(render_metrics_page(), encoding="utf-8")

    usage_rst = args.output.parent / "usage.rst"
    usage_rst.write_text(render_usage_page(), encoding="utf-8")

    config_rst = args.output.parent / "configuration.rst"
    config_rst.write_text(render_config_page(), encoding="utf-8")

    conf_py = args.output.parent / "conf.py"
    conf_py.write_text(render_conf_py(args.project), encoding="utf-8")

    (args.output.parent / "_static").mkdir(exist_ok=True)
    (args.output.parent / "_templates").mkdir(exist_ok=True)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
